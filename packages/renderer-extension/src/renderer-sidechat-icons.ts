const SVG = "http://www.w3.org/2000/svg";

/** Builds trusted constant artwork with DOM calls; no markup is parsed. */
export function sideChatIcon(
  document: Document,
  name: SideChatIcon,
  className = "",
): SVGSVGElement {
  const icon: IconDefinition = ICONS[name];
  const svg = document.createElementNS(SVG, "svg");
  const [, , width = "16", height = "16"] = icon.viewBox.split(" ");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  svg.setAttribute("width", width);
  svg.setAttribute("height", height);
  svg.setAttribute("viewBox", icon.viewBox);
  if (icon.fill) svg.setAttribute("fill", icon.fill);
  if (className) svg.setAttribute("class", className);
  for (const [tag, attributes] of icon.shapes) {
    const shape = document.createElementNS(SVG, tag);
    for (const [key, value] of Object.entries(attributes)) shape.setAttribute(key, value);
    svg.append(shape);
  }
  return svg;
}

/** Native menus draw each icon in a 16pt box. A 16-unit glyph gets the 20-unit menu inset. */
export function sideChatMenuIcon(name: SideChatIcon): string {
  const icon: IconDefinition = ICONS[name];
  const box = icon.viewBox === "0 0 16 16" ? "-2 -2 20 20" : icon.viewBox;
  const shapes = icon.shapes
    .map(
      ([tag, attributes]) =>
        `<${tag} ${Object.entries(attributes)
          .map(([key, value]) => `${key}="${value}"`)
          .join(" ")}/>`,
    )
    .join("");
  const fill = icon.fill ? ` fill="${icon.fill}"` : "";
  const markup = `<svg xmlns="${SVG}" width="20" height="20" viewBox="${box}"${fill}>${shapes}</svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(markup)}`;
}
